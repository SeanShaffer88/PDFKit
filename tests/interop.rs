//! Interop proof against a fixture produced by matplotlib
//! (tools/make_fixture.py): a mainstream producer's PDF — subset
//! fonts, ToUnicode CMaps, compressed content — that our parser must
//! read correctly. pdfinfo agrees with the fixture's shape (2 pages,
//! letter) and was used to validate it when generated.

use pdfkit::pdf::Document;

fn fixture() -> Vec<u8> {
    let path = format!(
        "{}/tests/fixtures/matplotlib.pdf",
        env!("CARGO_MANIFEST_DIR")
    );
    std::fs::read(&path).unwrap_or_else(|e| panic!("fixture: {e}"))
}

#[test]
fn matplotlib_fixture_structure_and_metadata() {
    let doc = Document::load(&fixture()).unwrap();
    assert_eq!(doc.pages.len(), 2);
    let (w, h) = (
        doc.pages[0].media_box[2] - doc.pages[0].media_box[0],
        doc.pages[0].media_box[3] - doc.pages[0].media_box[1],
    );
    assert!(
        (w - 612.0).abs() < 1.0 && (h - 792.0).abs() < 1.0,
        "size {w}x{h}"
    );
    assert_eq!(
        doc.info_string("Title").as_deref(),
        Some("PDFKit Test Fixture")
    );
    assert_eq!(doc.info_string("Author").as_deref(), Some("PDFKit Tests"));
}

#[test]
fn matplotlib_fixture_text_extracts() {
    let doc = Document::load(&fixture()).unwrap();
    let t0 = pdfkit::extract::page_text(&doc, &doc.pages[0]).unwrap();
    for needle in ["PDFKit", "Fixture", "quick brown fox", "0123456789"] {
        assert!(
            t0.contains(needle),
            "page 1 missing {needle:?} — got: {t0:?}"
        );
    }
    let t1 = pdfkit::extract::page_text(&doc, &doc.pages[1]).unwrap();
    assert!(t1.contains("Second Page"), "page 2: {t1:?}");
    assert!(t1.contains("Final page"), "page 2: {t1:?}");
}

/// Dump one of our generated PDFs for out-of-band validation with
/// pdfinfo/poppler (run locally; CI asserts the reader direction).
/// Enable with PK_DUMP_PDF=<path>.
#[test]
#[ignore = "writes a PDF for external (poppler) validation; PK_DUMP_PDF env"]
fn dump_pdf_for_poppler() {
    let out = match std::env::var("PK_DUMP_PDF") {
        Ok(p) => p,
        Err(_) => return,
    };
    let mut g = pdfkit::write::Generator {
        title: "Generated by PDFKit".into(),
        author: "Interop Check".into(),
        ..Default::default()
    };
    let p = g.add_page(612.0, 792.0).unwrap();
    g.draw_text(p, 72.0, 720.0, 24.0, "PDFKit writes valid PDFs")
        .unwrap();
    g.draw_text(
        p,
        72.0,
        690.0,
        12.0,
        "Validated by poppler pdfinfo + pdftotext.",
    )
    .unwrap();
    std::fs::write(&out, g.render().unwrap()).unwrap();
}
